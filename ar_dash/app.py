"""Receivables Health Dashboard: AR quality analytics on public SEC filings."""
from pathlib import Path

import pandas as pd
import plotly.graph_objects as go
import streamlit as st
import yaml

from pipeline import anomalies, ar_variance_bridge, build_facts, insight_summary

st.set_page_config(page_title="Receivables Health Dashboard", layout="wide")

INK, MUTED, ACCENT, POS, NEG, GRID = "#1f2937", "#6b7280", "#2563eb", "#059669", "#dc2626", "#e5e7eb"


@st.cache_data
def load():
    facts, dq = build_facts()
    return facts, dq, anomalies(facts)


def style(fig, height=360):
    fig.update_layout(height=height, margin=dict(l=10, r=10, t=30, b=10), plot_bgcolor="white",
                      paper_bgcolor="white", font=dict(color=INK, size=13), legend=dict(orientation="h", y=-0.15))
    fig.update_xaxes(showgrid=False, linecolor=GRID)
    fig.update_yaxes(gridcolor=GRID, zeroline=False)
    return fig


facts, dq, anom = load()
semantic = yaml.safe_load((Path(__file__).parent / "semantic_model.yaml").read_text())

st.title("Receivables Health Dashboard")
st.caption("Accounts receivable quality for 16 US-listed companies, built from SEC EDGAR XBRL 10-K data. "
           "Every metric comes from one governed definition in the semantic layer.")

with st.sidebar:
    st.header("Filters")
    sectors = sorted(facts.sector.unique())
    pick_sectors = st.multiselect("Sector", sectors, default=sectors)
    pool = facts[facts.sector.isin(pick_sectors)]
    tickers = sorted(pool.ticker.unique())
    ticker = st.selectbox("Company for drill-down", tickers, index=tickers.index("MSFT") if "MSFT" in tickers else 0)
    years = sorted(pool.fiscal_year.unique())
    yr = st.select_slider("Fiscal year", options=years, value=max(y for y in years if y <= 2025))

tab_over, tab_co, tab_var, tab_anom, tab_dq, tab_sem = st.tabs(
    ["Overview", "Company drill-down", "Variance analysis", "Anomalies", "Data quality", "Semantic model"])

# Overview -------------------------------------------------------------------
with tab_over:
    snap = pool[pool.fiscal_year == yr].dropna(subset=["dso_days"])
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Companies with data", f"{snap.ticker.nunique()}")
    c2.metric("Median DSO", f"{snap.dso_days.median():.0f} days")
    cov = snap.allowance_coverage_pct.dropna()
    c3.metric("Median allowance coverage", f"{cov.median():.1f}%" if len(cov) else "n/a")
    c4.metric("AR outgrowing revenue", f"{(snap.ar_minus_revenue_growth_pp > 5).sum()} companies",
              help="Receivables grew more than 5 pp faster than revenue")

    st.subheader(f"Days sales outstanding, FY{yr}")
    s = snap.sort_values("dso_days")
    colors = [ACCENT if t == ticker else "#93c5fd" for t in s.ticker]
    fig = go.Figure(go.Bar(x=s.dso_days, y=s.ticker, orientation="h", marker_color=colors,
                           text=[f"{v:.0f}" for v in s.dso_days], textposition="outside",
                           hovertemplate="%{y}: %{x:.1f} days<extra></extra>"))
    fig.update_xaxes(title="Days")
    st.plotly_chart(style(fig, 30 * len(s) + 80), use_container_width=True)

    st.subheader("Receivables growth vs revenue growth")
    sc = snap.dropna(subset=["ar_growth_pct", "revenue_growth_pct"])
    fig = go.Figure()
    lim = [min(sc.revenue_growth_pct.min(), sc.ar_growth_pct.min(), -10) - 5,
           max(sc.revenue_growth_pct.max(), sc.ar_growth_pct.max(), 10) + 5]
    fig.add_trace(go.Scatter(x=lim, y=lim, mode="lines", line=dict(color=MUTED, dash="dot"),
                             name="AR grows in line with revenue", hoverinfo="skip"))
    fig.add_trace(go.Scatter(x=sc.revenue_growth_pct, y=sc.ar_growth_pct, mode="markers+text", text=sc.ticker,
                             textposition="top center", marker=dict(size=11, color=ACCENT), name="Company",
                             hovertemplate="%{text}<br>Revenue %{x:.1f}%<br>AR %{y:.1f}%<extra></extra>"))
    fig.update_xaxes(title="Revenue growth (%)")
    fig.update_yaxes(title="Net receivables growth (%)")
    st.plotly_chart(style(fig, 420), use_container_width=True)
    st.caption("Points above the dotted line: receivables grew faster than sales, an early signal of slower collection.")

# Company drill-down ----------------------------------------------------------
with tab_co:
    g = facts[facts.ticker == ticker].sort_values("fiscal_year")
    st.subheader(f"{g.company.iloc[0]} ({ticker})")
    for line in insight_summary(facts, ticker):
        st.markdown(f"- {line}")
    st.caption("Insight lines are generated by rules over the semantic metrics, so each one traces back to a number below.")

    left, right = st.columns(2)
    with left:
        fig = go.Figure(go.Scatter(x=g.fiscal_year, y=g.dso_days, mode="lines+markers", line=dict(color=ACCENT, width=3),
                                   hovertemplate="FY%{x}: %{y:.1f} days<extra></extra>"))
        fig.update_layout(title="DSO (days)")
        st.plotly_chart(style(fig), use_container_width=True)
    with right:
        cg = g.dropna(subset=["allowance_coverage_pct"])
        if len(cg):
            fig = go.Figure(go.Scatter(x=cg.fiscal_year, y=cg.allowance_coverage_pct, mode="lines+markers",
                                       line=dict(color=POS, width=3), hovertemplate="FY%{x}: %{y:.2f}%<extra></extra>"))
            fig.update_layout(title="Allowance coverage (% of gross receivables)")
            st.plotly_chart(style(fig), use_container_width=True)
        else:
            st.info("No separately tagged allowance for this company, so coverage is not shown.")

    show = g[["fiscal_year", "revenue", "accounts_receivable_net", "allowance_for_credit_losses", "dso_days",
              "allowance_coverage_pct", "ar_minus_revenue_growth_pp"]].copy().astype(float)
    show["fiscal_year"] = show["fiscal_year"].astype(int)
    for c in ["revenue", "accounts_receivable_net", "allowance_for_credit_losses"]:
        show[c] = show[c] / 1e6
    show.columns = ["FY", "Revenue ($M)", "Net AR ($M)", "Allowance ($M)", "DSO (days)", "Coverage (%)",
                    "AR − revenue growth (pp)"]
    show = show.set_index("FY").map(lambda v: "–" if pd.isna(v) else f"{v:,.1f}")
    st.dataframe(show, use_container_width=True)

# Variance analysis -----------------------------------------------------------
with tab_var:
    st.subheader(f"What moved {ticker}'s receivables in FY{yr}?")
    b = ar_variance_bridge(facts, ticker, yr)
    if b is None:
        st.info("This company is missing revenue or receivables for the selected year or the year before.")
    else:
        vals = [b["start"], b["volume_effect"], b["collection_effect"], b["end"]]
        fig = go.Figure(go.Waterfall(
            x=[f"Net AR FY{yr-1}", "Revenue (volume) effect", "Collection (DSO) effect", f"Net AR FY{yr}"],
            y=[v / 1e6 for v in vals], measure=["absolute", "relative", "relative", "total"],
            increasing=dict(marker_color=NEG), decreasing=dict(marker_color=POS),
            totals=dict(marker_color=ACCENT), connector=dict(line=dict(color=GRID)),
            text=[f"{v/1e6:,.0f}" for v in vals], textposition="outside"))
        fig.update_yaxes(title="$M")
        st.plotly_chart(style(fig, 420), use_container_width=True)
        st.markdown(
            f"- **Revenue effect** ({b['volume_effect']/1e6:+,.0f}M): change in receivables if DSO had stayed at last year's level.\n"
            f"- **Collection effect** ({b['collection_effect']/1e6:+,.0f}M): change caused by collecting faster or slower.")
        st.caption("Bridge: ΔAR = ΔRevenue × DSO(prior)/365 + Revenue(current) × ΔDSO/365. The two effects add up exactly to the total change.")

# Anomalies -------------------------------------------------------------------
with tab_anom:
    st.subheader("Unusual DSO movements")
    st.caption("A year is flagged when a company's change in DSO is at least 2 robust standard deviations "
               "(median absolute deviation) away from its own history.")
    a = anom[anom.ticker.isin(pool.ticker)] if len(anom) else anom
    if len(a):
        a = a.copy()
        a["Direction"] = a.dso_change_days.map(lambda v: "Slower collection" if v > 0 else "Faster collection")
        a = a.rename(columns={"ticker": "Ticker", "fiscal_year": "FY", "dso_days": "DSO (days)",
                              "dso_change_days": "Δ DSO (days)", "robust_z": "Robust z",
                              "ar_minus_revenue_growth_pp": "AR − revenue growth (pp)"})
        st.dataframe(a.style.format({"DSO (days)": "{:.1f}", "Δ DSO (days)": "{:+.1f}", "Robust z": "{:+.1f}",
                                     "AR − revenue growth (pp)": "{:+.1f}"}), hide_index=True, use_container_width=True)
    else:
        st.info("No anomalies for the selected sectors.")

# Data quality ----------------------------------------------------------------
with tab_dq:
    st.subheader("Data quality log")
    sev_order = {"error": 0, "review": 1, "warning": 2, "info": 3}
    d = dq[dq.ticker.isin(pool.ticker)].copy()
    cols = st.columns(4)
    for i, sev in enumerate(sev_order):
        cols[i].metric(sev.capitalize(), int((d.severity == sev).sum()))
    d["order"] = d.severity.map(sev_order)
    st.dataframe(d.sort_values(["order", "ticker"]).drop(columns="order")
                 .rename(columns=str.capitalize), hide_index=True, use_container_width=True)
    rules = pd.DataFrame(semantic["data_quality_rules"]).rename(columns=str.capitalize)
    with st.expander("Rule definitions"):
        st.dataframe(rules, hide_index=True, use_container_width=True)

# Semantic model --------------------------------------------------------------
with tab_sem:
    st.subheader("Governed metric definitions")
    m = pd.DataFrame([{"Metric": k, "Formula": v["formula"], "Meaning": v.get("description", "")}
                      for k, v in semantic["metrics"].items()])
    st.dataframe(m, hide_index=True, use_container_width=True)
    b = pd.DataFrame([{"Base measure": k, "XBRL tags (in priority order)": ", ".join(v["xbrl_tags"]), "Type": v["type"]}
                      for k, v in semantic["base_measures"].items()])
    st.dataframe(b, hide_index=True, use_container_width=True)
    st.caption(f"Source: {semantic['source']}.")
